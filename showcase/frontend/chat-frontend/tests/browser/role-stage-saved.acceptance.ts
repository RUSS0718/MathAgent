import { expect, test } from '@playwright/test'

test('saved backend dual entry and history remain read-only after task failure', async ({ page, request }) => {
  const seed = await (await request.get('http://127.0.0.1:5182/_role-stage-fixture')).json()
  const before = await (await request.get('http://127.0.0.1:5182/_role-stage-audit')).json()
  const writes: string[] = []
  const errors: string[] = []
  page.on('request', req => { if (req.method() !== 'GET') writes.push(new URL(req.url()).pathname) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`/dashboard-assets/session/${seed.session_id}`)
  await page.locator('.execution-process > summary').click()
  const workbench = page.getByRole('region', { name: '对话式执行工作台' })
  const star = workbench.getByLabel('迷你星图角色成果', { exact: true })
    .getByRole('button', { name: /^查看方案规划 / })
  await star.click()
  const panel = page.getByRole('dialog', { name: '方案规划阶段成果' })
  await expect(panel).toContainText('保存目标第 2 版')
  await expect(panel).toContainText('执行遇到问题')
  await expect(panel).toContainText('不代表目标已完成')
  await expect(panel.locator('.katex')).not.toHaveCount(0)
  const current = await panel.innerText()
  expect(current).not.toContain('PRIVATE_ARGUMENT_MUST_NOT_LEAK')
  await panel.getByRole('button', { name: '关闭', exact: true }).click()
  const progress = workbench.getByRole('button', { name: '查看方案规划阶段成果', exact: true })
  await progress.last().click()
  await expect(panel).toContainText('保存目标第 2 版')
  await panel.getByRole('button', { name: '关闭', exact: true }).click()
  await progress.first().click()
  await expect(panel).toContainText('保存目标第 1 版')
  await expect(panel).not.toContainText('保存目标第 2 版')
  await expect(panel).toContainText('已替换')
  await panel.getByRole('button', { name: '查看当前成果', exact: true }).click()
  await expect(panel).toContainText('保存目标第 2 版')
  await panel.getByRole('button', { name: '关闭', exact: true }).click()
  await star.click()
  await expect(panel).toContainText('保存目标第 2 版')
  await page.screenshot({ path: '../../../artifacts/role-stage-199/saved-browser-panel.png' })
  const after = await (await request.get('http://127.0.0.1:5182/_role-stage-audit')).json()
  expect(after).toEqual(before)
  expect(before.worker_enabled).toBe(false)
  expect(before.calls).toEqual({})
  expect(writes.filter(path => path !== '/api/change_session')).toEqual([])
  expect(errors).toEqual([])
})
